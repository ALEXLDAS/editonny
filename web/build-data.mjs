import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';

const check = process.argv.includes('--check');
async function writeOrCheck(name, contents) {
  const destination = new URL(name, import.meta.url);
  if (check) {
    if (await readFile(destination, 'utf8') !== contents) throw new Error(`${name} is outdated: run npm run build.`);
  } else {
    await writeFile(destination, contents);
  }
}

const source = new URL('../skills/editonny/visuals/catalog.json', import.meta.url);
const catalog = JSON.parse(await readFile(source, 'utf8'));
if (!Array.isArray(catalog.scenes) || !catalog.scenes.length) throw new Error('Catalog has no scenes.');
const ids = new Set();
const scenes = catalog.scenes.map(scene => {
  if (!scene.id || !scene.name || ids.has(scene.id)) throw new Error(`Invalid or duplicate scene: ${scene.id}`);
  ids.add(scene.id);
  const { id, name, category, whenToUse, duration, format, layout, hidesCaptions } = scene;
  return { id, name, category, whenToUse, duration, format, layout, hidesCaptions: Boolean(hidesCaptions) };
});
await writeOrCheck('catalog.json', JSON.stringify({ version: catalog.version, scenes }, null, 2) + '\n');
const result = await build({
  absWorkingDir: fileURLToPath(new URL('../', import.meta.url)),
  entryPoints: ['web/app.mjs'],
  outfile: 'web/app.js',
  bundle: true,
  format: 'iife',
  platform: 'browser',
  target: 'es2022',
  charset: 'utf8',
  minify: true,
  write: false,
  banner: { js: '// Generated by npm run build. Edit the .mjs source modules.' },
});
await writeOrCheck('app.js', result.outputFiles[0].text);
console.log(`${scenes.length} scenes and guide ${check ? 'verified' : 'generated'} in web/.`);
